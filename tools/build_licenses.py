import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from rag import sources as S        # noqa: E402
from market import quotes as Q      # noqa: E402

MODEL = [
    ("Qwen3.5-4B (base weights, Qwen team)", "Apache-2.0", "VERIFIED (upstream model card)",
     "unsloth/Qwen3.5-4B-GGUF @ e87f176479d0855a907a41277aca2f8ee7a09523"),
    ("Qwen3.5-4B-Q4_K_M.gguf (Unsloth conversion)", "Apache-2.0 (inherits)", "VERIFIED",
     "sha256 00fe7986ff5f6b463e62455821146049db6f9313603938a70800d1fb69ef11a4"),
]
DEPS = [
    ("llama-cpp-python", "MIT", "runtime: in-process inference (Windows, i5-12400)"),
    ("psutil", "BSD-3-Clause", "runtime: peak RSS measurement"),
    ("jinja2", "BSD-3-Clause", "tests only: render the GGUF/HF chat templates"),
    ("tokenizers", "Apache-2.0", "tests/analysis only: token counting"),
    ("Ollama (optional server)", "MIT", "Phase 8 alternative runtime; not recommended on this machine"),
    ("LM Studio (optional server)", "proprietary freeware (terms of the vendor)", "Phase 8 alternative runtime"),
]


def _cell(x):
    return str(x).replace("|", "/").replace("\n", " ").strip()


def render():
    out = ["# LICENSES — registry (generated by tools/build_licenses.py; do not edit by hand)", "",
           "Generated from `src/rag/sources.py` and `src/market/quotes.py`. A test fails if this file "
           "and the live registries disagree.", "",
           "## Project code", "",
           "**Apache License 2.0** (`LICENSE`, `NOTICE`), chosen 2026-10-21 under the owner's delegation "
           "(D-0130). It covers only the original work in this repository. It does **not** cover the "
           "third-party material listed below and in `NOTICE`, which keeps its own terms:", "",
           "- `tests/fixtures/alpha_vantage/*.json`: verbatim Alpha Vantage API captures; Alpha Vantage "
           "terms (personal, non-commercial use). Not licensed to you by this project.",
           "- `configs/model-cards/*.json`: configuration files published by the model authors, under "
           "their licences.",
           "- Data and model outputs in `evidence/` keep the terms of the source they came from (tables below).",
           "",
           "## Model", "", "| Component | Licence | Status | Identity |", "|---|---|---|---|"]
    out += ["| %s | %s | %s | %s |" % tuple(map(_cell, r)) for r in MODEL]
    out += ["", "## Software dependencies (third-party, not vendored)", "",
            "| Package | Licence | Used for |", "|---|---|---|"]
    out += ["| %s | %s | %s |" % tuple(map(_cell, r)) for r in DEPS]
    out += ["", "## Data and research sources (`src/rag/sources.py`)", "",
            "| Key | Name | Trust | Enabled | Licence / terms (as recorded) |", "|---|---|---|---|---|"]
    for k, s in sorted(S.SOURCES.items()):
        out.append("| %s | %s | %s | %s | %s |" % (_cell(k), _cell(s.name), _cell(s.trust_level),
                                                 "yes" if s.enabled else "no", _cell(s.licence)[:300]))
    out += ["", "## Market-data providers (`src/market/quotes.py`)", "",
            "| Key | Enabled | Activation basis |", "|---|---|---|"]
    for k, p in sorted(Q.PROVIDERS.items()):
        out.append("| %s | %s | %s |" % (_cell(k), "yes" if p.enabled else "no",
                                         _cell(getattr(p, "activation_basis", None) or "—")))
    out += ["", "No market-data provider is LICENSED for machine use. Alpha Vantage is enabled on "
            "USER_ACCEPTED_RISK (its terms are silent), and TradingView prohibits machine use. See "
            "`docs/legal/`.", ""]
    return "\n".join(out)


if __name__ == "__main__":
    sys.stdout.write(render())
